#!/usr/bin/env python3
"""Turn the Website images canvas layout into site code.

Reads tools/art-layout.json (boards copied from the canvas with "Copy layout"),
writes css/art.css, and swaps the markup between the art markers in index.html.

Each image box is sized to take in every shape (not just the photo), so shapes
never get clipped by the screen edge and the layout reserves the right space.
Sizing of the boxes themselves (max width, bleed into margins) lives by hand in
css/layout.css, so this script only places things inside each box.

Run from the repo root:  python3 tools/build-art.py
"""
import json, math, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
LAYOUT = json.loads((ROOT / 'tools/art-layout.json').read_text())

TONES = {
    'bwc':      [[.05,.20,.52,.84,1],[.05,.20,.52,.84,1],[.05,.20,.52,.84,1]],
    'washlo':   [[.29,.976],[.29,.965],[.36,.945]],
    'wash':     [[.1686,.9765],[.1686,.9647],[.2275,.9451]],
    'washmid':  [[.13,.32,.553,.785,.976],[.13,.32,.547,.776,.965],[.20,.37,.575,.78,.945]],
    'washdeep': [[.09,.27,.53,.80,.976],[.09,.27,.52,.79,.965],[.165,.33,.56,.80,.945]],
}

def aabb(e):
    if not e.get('rot'):
        return e['x'], e['y'], e['x'] + e['w'], e['y'] + e['h']
    a = math.radians(e['rot']); c, s = math.cos(a), math.sin(a)
    cx, cy = e['x'] + e['w'] / 2, e['y'] + e['h'] / 2
    pts = [(cx + dx*c - dy*s, cy + dx*s + dy*c) for dx in (-e['w']/2, e['w']/2) for dy in (-e['h']/2, e['h']/2)]
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    return min(xs), min(ys), max(xs), max(ys)

def img_size(path):
    import subprocess
    out = subprocess.run(['sips', '-g', 'pixelWidth', '-g', 'pixelHeight', str(path)], capture_output=True, text=True).stdout
    w = int(re.search(r'pixelWidth: (\d+)', out).group(1)); h = int(re.search(r'pixelHeight: (\d+)', out).group(1))
    return w, h

def pct(v):
    return f'{v:.3f}'.rstrip('0').rstrip('.') + '%'

css = ['/* Generated by tools/build-art.py from tools/art-layout.json. Do not edit by hand. */',
       '.art { position: relative; }',
       '.art > * { position: absolute; display: block; margin: 0; }',
       '.art__photo { object-fit: cover; }']
filters_used = set()
html_blocks = {}

for name, board in LAYOUT.items():
    els = board['els']
    boxes = [aabb(e) for e in els]
    if board.get('box') == 'board':
        # the box is the canvas board itself (its dashed line); shapes should sit inside it
        aw, ah = map(float, board['ratio'].split(':'))
        x0, y0, W, H = 0.0, 0.0, 100.0, 100.0 * ah / aw
        out = [e for e, b in zip(els, boxes) if b[0] < -0.5 or b[1] < -0.5 or b[2] > W + 0.5 or b[3] > H + 0.5]
        for e in out: print(f'NOTE {name}: {e["t"]} {e["id"]} sits partly outside the board edge')
    else:
        # the box takes in every shape
        x0, y0 = min(b[0] for b in boxes), min(b[1] for b in boxes)
        x1, y1 = max(b[2] for b in boxes), max(b[3] for b in boxes)
        W, H = x1 - x0, y1 - y0
    sel = f'.art--{name}'
    css.append(f'\n/* {name}: box spans {W:.2f} x {H:.2f} canvas units; at full size {W*board["desktop_px_per_unit"]:.0f}px wide */')
    css.append(f'{sel} {{ aspect-ratio: {W:.3f} / {H:.3f}; --art-max: {W*board["desktop_px_per_unit"]:.0f}px; }}')
    markup = []
    for i, e in enumerate(els, 1):
        cls = f'art__{i}'
        rules = [f'left: {pct((e["x"]-x0)/W*100)}', f'top: {pct((e["y"]-y0)/H*100)}', f'width: {pct(e["w"]/W*100)}']
        t = e['t']
        if t in ('circle', 'tear'):
            rules.append('aspect-ratio: 1')
        else:
            rules.append(f'height: {pct(e["h"]/H*100)}')
        if t == 'circle':
            rules.append('border-radius: 50%')
        elif t == 'tear':
            rules.append('border-radius: 50% 50% 50% 4%')
        elif t == 'pill':
            rules.append('border-radius: 9999px')
        if t != 'photo':
            rules.append(f'background: {e["c"]}')
        if e.get('rot'):
            rules.append(f'transform: rotate({e["rot"]:g}deg)')
        if t == 'photo':
            if e.get('zoom', 1) != 1:
                print(f'WARNING {name}: photo zoom {e["zoom"]} is not supported yet; using 1')
            # canvas px/py slide the photo in its frame (fraction of frame size); convert to object-position
            iw0, ih0 = img_size(ROOT / board['img_src'])
            ia, fa = iw0 / ih0, e['w'] / e['h']
            iw, ih = (e['h'] * ia, e['h']) if ia > fa else (e['w'], e['w'] / ia)
            def op(off, frame, img):
                spare = img - frame
                if spare <= 0.001: return 50
                off = max(-spare/2, min(spare/2, off * frame))
                return round(50 - off / spare * 100, 2)
            rules.append(f'object-position: {op(e.get("px",0), e["w"], iw):g}% {op(e.get("py",0), e["h"], ih):g}%')
            f = []
            if e.get('br', 100) != 100: f.append(f'brightness({e["br"]/100:g})')
            if e.get('ct', 100) != 100: f.append(f'contrast({e["ct"]/100:g})')
            tone = e.get('tone', 'bw')
            if tone == 'bw': f.append('grayscale(1)')
            elif tone in TONES: f.append(f'url(#lt-tone-{tone})'); filters_used.add(tone)
            if f: rules.append('filter: ' + ' '.join(f))
            markup.append(f'<img class="art__photo {cls}" src="{board["img_src"]}" alt="{board.get("alt","")}" loading="{board.get("loading","lazy")}" />')
        else:
            markup.append(f'<span class="{cls}"></span>')
        css.append(f'{sel} .{cls} {{ ' + '; '.join(rules) + '; }')
    html_blocks[name] = f'<div class="art art--{name}">\n' + '\n'.join('  ' + m for m in markup) + '\n</div>'

(ROOT / 'css/art.css').write_text('\n'.join(css) + '\n')

filt = ['<svg class="art-filters" width="0" height="0" aria-hidden="true" focusable="false" style="position:absolute">']
for tone in sorted(filters_used):
    tv = TONES[tone]
    filt.append(f'  <filter id="lt-tone-{tone}" color-interpolation-filters="sRGB">'
                '<feColorMatrix type="matrix" values=".2126 .7152 .0722 0 0 .2126 .7152 .0722 0 0 .2126 .7152 .0722 0 0 0 0 0 1 0"/>'
                '<feComponentTransfer>' + ''.join(f'<feFunc{ch} type="table" tableValues="{" ".join(map(str, tv[i]))}"/>' for i, ch in enumerate('RGB')) +
                '</feComponentTransfer></filter>')
filt.append('</svg>')
html_blocks['filters'] = '\n'.join(filt)

page = (ROOT / 'index.html').read_text()
for key, block in html_blocks.items():
    pat = re.compile(rf'(<!-- art:{key} -->)(.*?)(<!-- /art:{key} -->)', re.S)
    if not pat.search(page):
        raise SystemExit(f'Missing <!-- art:{key} --> markers in index.html')
    indent = re.search(rf'\n([ \t]*)<!-- art:{key} -->', page).group(1)
    body = '\n'.join(indent + l if l else l for l in block.split('\n'))
    page = pat.sub(lambda m: m.group(1) + '\n' + body + '\n' + indent + m.group(3), page)
(ROOT / 'index.html').write_text(page)
print('Built', ', '.join(LAYOUT), '| filters:', ', '.join(sorted(filters_used)) or 'none')
